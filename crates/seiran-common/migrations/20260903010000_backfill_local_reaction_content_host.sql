-- 7d385f1（絵文字リアクションをホスト付き形式 `:shortcode@host:` へ移行）は既存データを
-- 非移行のまま残したため、ローカルアクターが過去に付けたリアクションの一部が
-- レガシー形式 `:shortcode:`（ホスト情報なし）のまま残っていた。同一絵文字が新旧表記で
-- 別々の `content` として扱われ、リアクションチップ集計・絵文字ピッカー「よく使う」ランキング
-- （`GROUP BY content`）で二重集計・二重表示される不具合があったため、ローカルアクター分のみ
-- 一括で `:shortcode@.:` へ書き換える。
--
-- リモートアクターが送ってきたレガシー形式（ホスト無しのまま連合してきた古いFedi実装からの
-- 受信分）は対象外。実行者のドメインが不明なため機械的に補完できず、読み出し側の
-- ローカル相当フォールバック解釈に委ねる。
UPDATE reactions r
SET content = regexp_replace(r.content, '^:([^:@]+):$', ':\1@.:')
FROM actors a
WHERE r.actor_id = a.id
  AND a.actor_type = 'local'
  AND r.content ~ '^:[^:@]+:$';
